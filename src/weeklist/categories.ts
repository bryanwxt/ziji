const BY_WORD = new Map<string, string>();
for (const [cat, words] of Object.entries(CATEGORIES)) for (const w of words) if (!BY_WORD.has(w)) BY_WORD.set(w, cat);
// food and drink are one 「吃/喝」 world for a blank: 「我想喝一杯＿」 can't tell a drink from a soup
const SAME: Readonly<Record<string, string>> = { drink: 'food' };

/** A noun's category, or undefined when the map doesn't know it. */
export const categoryOf = (word: string): string | undefined => { const c = BY_WORD.get(word); return c && (SAME[c] ?? c); };

// categories a blank can't always tell apart: 烤鸭子 and 烤鸡翅, 炒豆芽 and a plant's 豆芽
const NEAR: readonly (readonly [string, string])[] = [['food', 'animal'], ['food', 'plant']];

/** Two words of one category, or of near ones: one may fit a blank the other fills. */
export const sameCategory = (a: string, b: string): boolean => {
  const ca = categoryOf(a);
  const cb = categoryOf(b);
  return !!ca && !!cb && a !== b && (ca === cb || NEAR.some(([x, y]) => (ca === x && cb === y) || (ca === y && cb === x)));
};
