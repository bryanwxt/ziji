export { voiceQuality };

/** The voice in use, and its tier for the parent's screens (spec 2026-10-12 §5). */
const useVoice = (v: SpeechSynthesisVoice | null): SpeechSynthesisVoice | null => {
  voice = v;
  noteVoice(v);
  return v;
};

/** The parent's pick (Settings → Voice), by voiceURI; null: the clearest the iPad has. */
let preferred: string | null = null;
export function setPreferredVoice(uri: string | null): void {
  preferred = uri;
  if (available()) useVoice(pickVoice(speechSynthesis.getVoices()));
}
/** The voice speaking now, for the parent's Voice setting. */
export const currentVoice = (): SpeechSynthesisVoice | null => voice;
/** The Mandarin voices this iPad lets the app use, clearest first. */
export function chineseVoices(): SpeechSynthesisVoice[] {
  if (!available()) return [];
  return speechSynthesis.getVoices().filter((v) => /^zh/i.test(v.lang) && !/HK|TW/i.test(v.lang)).sort((a, b) => voiceQuality(b) - voiceQuality(a));
}

export function pickVoice(voices: SpeechSynthesisVoice[]): SpeechSynthesisVoice | null {
  const chosen = preferred ? voices.find((v) => v.voiceURI === preferred) : undefined;
  if (chosen) return chosen;
  const mainland = voices.filter((v) => /^zh[-_]CN/i.test(v.lang)).sort((a, b) => voiceQuality(b) - voiceQuality(a) || Number(b.localService) - Number(a.localService));
  return (
    mainland[0] ??
    voices.find((v) => /^zh/i.test(v.lang) && !/HK|TW/i.test(v.lang)) ??
    null
  );
}

/** Voices load asynchronously on iPad Safari; wait briefly for them. */
export async function loadChineseVoice(timeoutMs = 1500, pref: string | null = null): Promise<SpeechSynthesisVoice | null> {
  preferred = pref;
  if (!available()) return useVoice(null);
  // the iPad can add voices after the first list (a downloaded Enhanced one): pick again whenever the list changes
  speechSynthesis.addEventListener?.('voiceschanged', () => { useVoice(pickVoice(speechSynthesis.getVoices()) ?? voice); });
  useVoice(pickVoice(speechSynthesis.getVoices()));
  if (!voice) {
    useVoice(await new Promise<SpeechSynthesisVoice | null>((resolve) => {
      const done = () => resolve(pickVoice(speechSynthesis.getVoices()));
      speechSynthesis.addEventListener?.('voiceschanged', done, { once: true });
      setTimeout(done, timeoutMs);
    }));
  }
  return voice;
}

/** One or two characters on their own go by in a blink: they are said a quarter slower (parent, 2026-10-05: placement's listening questions). */
export const SHORT_WORD_PACE = 0.75;
const isShortWord = (text: string) => {
  const han = Array.from(text).filter((ch) => /\p{Script=Han}/u.test(ch)).length;
  return han > 0 && han <= 2;
};

/**
 * What the voice is given for a lone character: a common 多音字 is said as a character read only the way the card teaches
 * (调 tiáo → 条), so the voice can't pick its other reading (parent, 2026-10-05). Generated by scripts/gen-say-as.ts.
 */
export function spokenAs(text: string, reading?: string): string {
  const { sayAs, poly, plain } = SAY_AS as { sayAs: Record<string, string>; poly: Record<string, string>; plain: Record<string, string> };
  // a character said on its own between pauses (写一写's "长，长城的，长") is said as taught too
  if (text.includes('，')) return text.split('，').map((part) => (Array.from(part).length === 1 ? spokenAs(part, reading) : part)).join('，');
  if (!(text in poly)) return text;
  if (reading && reading !== poly[text]) return plain[reading] ?? text;
  return sayAs[text] ?? text;
}

/**
 * What is said for a line: a lone character no voice can be steered on (sayAs.json's `unsure`: 爪 is zhuǎ on his card, zhǎo
 * to the voices) is said as its card's first 组词 instead (爪子), when it is wanted at its card's reading; so is each lone piece
 * of a line built from pieces, unless another piece already says it (写一写's "爪，爪子的，爪" stays). `avoid`: words it must not
 * be said as, because they are the answer on screen (连一连's 切 joins 菜: it is said as 切开, not 切菜), and `endings`: nor as
 * one ending in a tile it could join (茄子 when 子 is on the board); with none left, the character is said alone. A bound
 * character (kidGloss.ts boundPair: 番 → 番茄) is said as its pair the same way, first.
 */
export function loneSpoken(text: string, reading?: string, avoid: readonly string[] = [], endings: readonly string[] = [], { voice = false } = {}): string {
  const { poly, words } = SAY_AS as { poly: Record<string, string>; words?: Record<string, string[]> };
  if (text.includes('，')) {
    const parts = text.split('，');
    // a cue whose word already says it (了，为了的，了): its lone pieces stay bare (review 2026-10-15), for their clips. Not on
    // the iPad voice (`voice`): there bare 爪 is zhǎo beside 爪子's zhuǎ (parent 2026-10-15), so it is said as its word too
    return parts.map((part, i) => {
      const ch = part.trim();
      if (Array.from(ch).length !== 1) return part;
      const keep = !(voice && words?.[ch]) && parts.some((p, j) => j !== i && Array.from(p.trim()).length > 1 && p.includes(ch));
      return keep ? part : loneSpoken(part, reading, avoid, endings);
    }).join('，');
  }
  const t = text.trim();
  // a bound character (kidGloss.ts: 番 lives only in 番茄) is said as its pair, the word his card and questions teach it in
  const pair = boundPair(t);
  if (reading && reading !== (pair ? kidGlossReading(t) : poly[t])) return text;
  const said = [...new Set([...(pair ? [pair] : []), ...(words?.[t] ?? [])])];
  return said.find((w) => !avoid.includes(w) && !endings.some((e) => w.endsWith(e))) ?? text;
}

let player: ClipPlayer = createClipPlayer({
  context: audioContext,
  load: (id) => fetch(clipUrl(id)).then((r) => (r.ok ? r.arrayBuffer() : Promise.reject(new Error(`clip ${id}: ${r.status}`)))),
});
/** For tests: a stand-in player. */
export function setClipPlayer(p: ClipPlayer): void {
  player = p;
}

/** A line as it is said: by clips (`steps`, saying `text`), else by the iPad voice (`voiced`, also when a clip fails). */
type Line = { text: string; voiced: string; reading?: string };
type SayOpts = { reading?: string; avoid?: readonly string[]; endings?: readonly string[] };

/**
 * How a line is said. A lone unsure character (爪, 切) with its own clip at its card's reading (cut out of its 组词 by the
 * same voice: scripts/audio inventory) plays that clip, so it sounds the same alone as in its word; on the iPad voice it is
 * still said as its 组词. A bound character (爪 → 爪子) is said as its pair first either way.
 */
function said(line: string, { reading, avoid, endings }: SayOpts): Line & { steps: ClipStep[] | null } {
  const { poly, words } = SAY_AS as { poly: Record<string, string>; words?: Record<string, string[]> };
  const t = line.trim();
  const voiced = loneSpoken(line, reading, avoid, endings, { voice: true });
  if (words?.[t] && !boundPair(t) && (reading ?? poly[t]) === poly[t]) {
    const own = clipPlan(t, poly[t]);
    if (own) return { text: t, voiced, reading, steps: own };
  }
  const text = loneSpoken(line, reading, avoid, endings);
  return { text, voiced, reading, steps: clipPlan(text, reading) };
}
/** Lines queued behind a clip (or behind the iPad voice while a clip waits): said in order, one at a time. */
let after: Line[] = [];
let clipBusy = false;
const ttsBusy = () => available() && (live.size > 0 || waiting !== null);

/**
 * Say Chinese text: the neural voice's clip when there is one (spec 2026-10-06 §4), else the iPad voice. It cuts off whatever
 * is playing, unless `queue` (then it waits its turn: the character, then its usage line). `reading` is the pinyin a lone
 * character is taught with, when the screen knows it. While he is being recorded it says nothing (final review C1): a peek or
 * a line on screen must never end up in his take.
 */
export function speak(text: string, { queue = false, reading, avoid, endings }: { queue?: boolean } & SayOpts = {}): void {
  if (recordingNow()) return;
  const { steps, ...line } = said(text, { reading, avoid, endings });
  if (queue && (clipBusy || after.length > 0 || (ttsBusy() && steps))) {
    after.push(line);
    return;
  }
  if (!steps) {
    // the iPad voice: a tap still cuts off a clip and what was queued behind it (final review). Not the whole stopSpeaking(),
    // so ttsSpeak still sees the voice busy and waits its moment after the cancel
    if (!queue) { after = []; clipBusy = false; setClipActive(false); player.stop(); }
    ttsSpeak(line.voiced, { queue, reading });
    return;
  }
  if (!queue) stopSpeaking();
  playClip(steps, line);
}

function playClip(steps: ClipStep[], line: Line): void {
  clipBusy = true;
  setClipActive(true);
  void player.play(steps, () => setSpeaking(true)).then((r) => {
    if (r === 'stopped') return; // whoever stopped it has reset everything
    clipBusy = false;
    setClipActive(false);
    if (r === 'failed') { ttsSpeak(line.voiced, { queue: true, reading: line.reading }); return; } // never silent
    setSpeaking(false);
    drain();
  });
}

/** The next queued line, once nothing is playing. */
function drain(): void {
  if (clipBusy || ttsBusy()) return;
  const next = after.shift();
  if (!next) return;
  const steps = clipPlan(next.text, next.reading);
  if (steps) playClip(steps, next);
  else ttsSpeak(next.voiced, { queue: true, reading: next.reading });
}

/** Fetch a lesson's clips ahead, so they play at once and offline (the service worker keeps them). */
export function prefetchWords(words: { text: string; pinyin?: string; examples?: { text: string }[] }[]): void {
  const ids = new Set<string>();
  const add = (text: string, reading?: string) => { for (const s of said(text, { reading }).steps ?? []) if ('id' in s) ids.add(s.id); };
  for (const w of words) {
    add(w.text, w.pinyin);
    for (const e of w.examples ?? []) add(e.text);
  }
  if (ids.size) player.prefetch([...ids]);
}

/** The iPad's own voice (speechSynthesis): lines with no clip, and the fallback when a clip fails. */
function ttsSpeak(text: string, { queue = false, reading }: { queue?: boolean; reading?: string } = {}): void {
  if (!available()) return;
  text = spokenAs(text, reading);
  if (waiting) {
    // A tap is waiting for Safari to finish cancelling: a queued line joins it, a new tap replaces it.
    waiting.texts = queue ? [...waiting.texts, text] : [text];
    return;
  }
  if (!queue) {
    const busy = speechSynthesis.speaking || speechSynthesis.pending;
    epoch++;
    speechSynthesis.cancel();
    live.clear(); // as stopSpeaking: a cancelled utterance ending late says nothing about this one (final review I3)
    setSpeaking(false); // a cancelled utterance may never say it ended
    if (busy) {
      // Safari drops or clips a voice started straight after cancelling one that was playing (parent, 2026-10-05: a sound
      // button tapped again was sometimes silent, sometimes cut short), so it is said a moment later.
      const w: Waiting = { texts: [text], timer: setTimeout(() => {
        waiting = null;
        for (const t of w.texts) say(t);
      }, AFTER_CANCEL_MS) };
      waiting = w;
      return;
    }
  }
  say(text);
}

/** How long Safari is given to finish cancelling before the next voice starts. */
const AFTER_CANCEL_MS = 120;
type Waiting = { texts: string[]; timer: ReturnType<typeof setTimeout> };
let waiting: Waiting | null = null;

/** Bumped whenever the app itself cancels speech (a new tap, leaving a screen): a voice it cut off isn't said again. */
let epoch = 0;
/** How long a voice has to start before it counts as dropped. */
const START_CHECK_MS = 500;

function say(text: string, retry = true): void {
  const u = new SpeechSynthesisUtterance(text);
  let started = false;
  const done = () => {
    if (!live.delete(u)) return; // a line already cancelled ending late: it says nothing about what is playing now
    setSpeaking(false);
    if (live.size === 0 && !waiting) drain(); // a line queued behind the iPad voice
  };
  u.onstart = () => {
    started = true;
    setSpeaking(true);
  };
  u.onend = done;
  u.onerror = done;
  live.add(u);
  u.lang = 'zh-CN';
  u.rate = isShortWord(text) ? Math.round(rate * SHORT_WORD_PACE * 100) / 100 : rate;
  if (voice) u.voice = voice;
  speechSynthesis.speak(u);
  // Safari can drop a voice without a word (a late cancel from the tap before it): one that hasn't started, with nothing else
  // playing and no cancel of ours since, is said once more (parent, 2026-10-05: the speak button needed a second press)
  if (!retry) return;
  const mine = epoch;
  setTimeout(() => {
    if (started || mine !== epoch || !available() || speechSynthesis.speaking) return;
    live.delete(u);
    say(text, false);
  }, START_CHECK_MS);
}

/** Silence any speech in progress, clip or voice, and drop what was queued (before recording him, and when leaving a screen). */
export function stopSpeaking(): void {
  after = [];
  clipBusy = false;
  setClipActive(false);
  player.stop();
  epoch++;
  if (waiting) clearTimeout(waiting.timer);
  waiting = null;
  if (available()) speechSynthesis.cancel();
  live.clear();
  setSpeaking(false);
}

/** iOS only allows speech after a user gesture; call this from the first tap. */
export function primeSpeech(): void {
  audioContext(); // inside his tap: the clips' audio may start
  if (!available()) return;
  const u = new SpeechSynthesisUtterance(' ');
  u.volume = 0;
  speechSynthesis.speak(u);
}
